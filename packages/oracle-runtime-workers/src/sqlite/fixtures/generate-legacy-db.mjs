// @ts-check
/* global URL, console */
/**
 * Builds `legacy-db.ts` — a SQLite file produced by the ORIGINAL Node runtime
 * stack (`@ixo/sqlite-saver` on `better-sqlite3`, plus the Node runtime's
 * `sessions` DDL) so the Workers port can prove it reads a real user's `.db`.
 *
 * Node-only script (plain JS so the Workers package's tsc never tries to
 * type-check `node:fs` or follow the workspace import). Run with:
 *
 *   cd packages/oracle-runtime-workers
 *   node_modules/.bin/tsx --tsconfig src/sqlite/fixtures/tsconfig.json src/sqlite/fixtures/generate-legacy-db.mjs
 *
 * `fixtures/tsconfig.json` maps `@ixo/logger` to a console stub because that
 * workspace package is not built in a fresh checkout. Everything else resolves
 * from `packages/sqlite-saver/node_modules`.
 */
import { AIMessage, HumanMessage } from '@langchain/core/messages';
import { emptyCheckpoint, TASKS, uuid6 } from '@langchain/langgraph-checkpoint';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const LEGACY_THREAD_ID = 'legacy-thread-1';
const LEGACY_SESSION_ID = 'legacy-thread-1';
const LEGACY_ROOM_ID = '!legacyroom:devmx.ixo.earth';

const here = dirname(fileURLToPath(import.meta.url));
// Computed specifier: keeps tsc from pulling the Node package into this program.
const saverEntry = new URL(
  '../../../../sqlite-saver/src/index.ts',
  import.meta.url,
).href;
const { SqliteSaver } = await import(saverEntry);

const dir = mkdtempSync(join(tmpdir(), 'qiforge-legacy-db-'));
const dbPath = join(dir, 'legacy.db');
const saver = SqliteSaver.fromConnString(dbPath);

// Same DDL as the Node runtime's `initializeSessionsAndCallsTables`.
saver.db.exec(`
  CREATE TABLE IF NOT EXISTS sessions (
    session_id TEXT PRIMARY KEY,
    title TEXT,
    last_updated_at TEXT NOT NULL,
    created_at TEXT NOT NULL,
    oracle_name TEXT NOT NULL,
    oracle_did TEXT NOT NULL,
    oracle_entity_did TEXT NOT NULL,
    last_processed_count INTEGER,
    user_context TEXT,
    room_id TEXT,
    slack_thread_ts TEXT
  );
  CREATE TABLE IF NOT EXISTS calls (
    call_id TEXT PRIMARY KEY,
    session_id TEXT NOT NULL,
    created_at TEXT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS idx_sessions_updated ON sessions(last_updated_at);
  CREATE INDEX IF NOT EXISTS idx_calls_session ON calls(session_id);
`);
saver.db
  .prepare(
    `INSERT INTO sessions (session_id, title, last_updated_at, created_at, oracle_name, oracle_did,
       oracle_entity_did, last_processed_count, user_context, room_id, slack_thread_ts)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
  )
  .run(
    LEGACY_SESSION_ID,
    'Legacy conversation',
    '2026-01-02T10:00:00.000Z',
    '2026-01-01T09:00:00.000Z',
    'Legacy Oracle',
    'did:ixo:legacyoracle',
    'did:ixo:entity:legacy',
    2,
    JSON.stringify({ name: 'Legacy User' }),
    LEGACY_ROOM_ID,
    null,
  );

// Checkpoint 0: the user's first message.
const human = new HumanMessage({
  id: 'legacy-msg-human-1',
  content: 'Hello from the Node runtime',
  additional_kwargs: {
    timestamp: '2026-01-01T09:00:01.000Z',
    msgFromMatrixRoom: true,
  },
});
const checkpoint0 = {
  ...emptyCheckpoint(),
  id: uuid6(0),
  channel_values: { messages: [human], loadedPlugins: ['weather'] },
};
let config = await saver.put(
  { configurable: { thread_id: LEGACY_THREAD_ID } },
  checkpoint0,
  {
    source: 'input',
    step: -1,
    parents: {},
  },
);

// Checkpoint 1: assistant reply; pending writes on the first checkpoint.
await saver.putWrites(
  config,
  [['someChannel', { answer: 42 }]],
  'legacy-task-1',
);
const ai = new AIMessage({
  id: 'legacy-msg-ai-1',
  content: 'Hello from the Node runtime, human',
  additional_kwargs: { timestamp: '2026-01-01T09:00:05.000Z' },
});
const checkpoint1 = {
  ...emptyCheckpoint(),
  id: uuid6(1),
  channel_values: { messages: [human, ai], loadedPlugins: ['weather'] },
  channel_versions: { messages: 2 },
};
config = await saver.put(config, checkpoint1, {
  source: 'loop',
  step: 0,
  parents: {},
});
await saver.putWrites(config, [[TASKS, 'legacy-send-1']], 'legacy-task-2');

saver.close();

const bytes = readFileSync(dbPath);
rmSync(dir, { recursive: true, force: true });

const out = join(here, 'legacy-db.ts');
const base64 = bytes.toString('base64');
writeFileSync(
  out,
  `/**
 * A SQLite file written by the Node runtime stack (\`@ixo/sqlite-saver\` on
 * \`better-sqlite3\` + the Node \`sessions\` DDL). Generated by
 * \`generate-legacy-db.mjs\` — do not edit by hand; re-run the generator.
 *
 * Contents: thread '${LEGACY_THREAD_ID}' with two checkpoints (ids
 * ${checkpoint0.id} and ${checkpoint1.id}), one human + one AI message, one
 * pending write on the first checkpoint, one TASKS write on the second, and a
 * sessions row '${LEGACY_SESSION_ID}' in room '${LEGACY_ROOM_ID}'.
 */
export const LEGACY_THREAD_ID = ${JSON.stringify(LEGACY_THREAD_ID)};
export const LEGACY_SESSION_ID = ${JSON.stringify(LEGACY_SESSION_ID)};
export const LEGACY_ROOM_ID = ${JSON.stringify(LEGACY_ROOM_ID)};
export const LEGACY_CHECKPOINT_IDS = [${JSON.stringify(checkpoint0.id)}, ${JSON.stringify(checkpoint1.id)}] as const;
export const LEGACY_DB_BYTE_LENGTH = ${bytes.byteLength};
export const LEGACY_DB_BASE64 =
  ${JSON.stringify(base64)};

export function legacyDbBytes(): Uint8Array {
  const binary = atob(LEGACY_DB_BASE64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return bytes;
}
`,
);
console.log(
  `wrote ${out} (${bytes.byteLength} bytes, checkpoints ${checkpoint0.id}, ${checkpoint1.id})`,
);
