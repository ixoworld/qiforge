/**
 * Golden values generated by executing the Evals Engine's own implementations
 * (packages/udid-validator/dist/{cid,canonical}.js and
 * packages/evidence-processing/dist/canonical.js) against these exact inputs.
 * They pin byte-identity of the mirrored conventions — do not update them
 * without re-running the engine code.
 */
const GOLDEN_TRACE_DOC = {
  schema: 'oracle.agent-trace.v1',
  sessionId: 's-1',
  requestId: 'r-1',
  messageCount: 4,
  toolCalls: [
    {
      id: 'call-1',
      name: 'get_weather',
      args: { city: 'Zug', units: 'celsius' },
      output: '{"tempC":21}',
      status: 'ok',
    },
  ],
};
const GOLDEN_TRACE_CANONICAL =
  '{"messageCount":4,"requestId":"r-1","schema":"oracle.agent-trace.v1","sessionId":"s-1","toolCalls":[{"args":{"city":"Zug","units":"celsius"},"id":"call-1","name":"get_weather","output":"{\\"tempC\\":21}","status":"ok"}]}';
const GOLDEN_TRACE_CID =
  'bafkreicnjexn52wnj7ktw2wueibovb25xivrjakk3z2asohaps7dgsnrrm';
const GOLDEN_HELLO_CID =
  'bafkreifzjut3te2nhyekklss27nh3k72ysco7y32koao5eei66wof36n5e';

const GOLDEN_PACKET = {
  schema: 'oracle.structured-fact-packet.v1',
  packetId: 'urn:ixo:evidence:test-1',
  claimId: 'claim-1',
  facts: [
    {
      factId: 'fact:1',
      factType: 'coding_task.tests_passed',
      statement: 'All 27 tests passed.',
      subject: 'urn:test:run:1',
      predicate: 'conclusion',
      object: 'success',
      polarity: 'supports',
      modality: 'reported',
      source: {
        evidenceId: 'urn:ixo:evidence:test-1',
        locator: '$.summary',
        origin: { provenanceClass: 'client_assisted' },
      },
      quality: 'usable',
    },
  ],
};
const GOLDEN_PACKET_DIGEST =
  'sha256:952de0965e8d4118bb159e5d81f0a3e0774522a4348c6b0c9ae785331af77256';

/** History that serializes to exactly GOLDEN_TRACE_DOC (4 messages, 1 call). */
function goldenHistory(): BaseMessage[] {
  return [
    new HumanMessage('What is the weather in Zug?'),
    new AIMessage({
      content: '',
      tool_calls: [
        {
          id: 'call-1',
          name: 'get_weather',
          args: { city: 'Zug', units: 'celsius' },
        },
      ],
    }),
    new ToolMessage({
      content: '{"tempC":21}',
      tool_call_id: 'call-1',
      name: 'get_weather',
    }),
    new AIMessage('It is 21°C in Zug.'),
  ];
}

function traceCtx(
  messages: BaseMessage[],
  overrides: Partial<RuntimeContext> = {},
): RuntimeContext {
  return makeRuntimeContext({
    session: {
      id: 's-1',
      client: 'portal',
      requestId: 'r-1',
      roomId: '!room:ixo.world',
    },
    history: {
      messages,
      recent: (n: number) => messages.slice(-n),
      userContext: {},
      state: { messages },
    },
    ...overrides,
  });
}

describe('content-cid (engine convention mirror)', () => {
  it('canonicalizes byte-identically to the engine', () => {
    expect(canonicalJsonString(GOLDEN_TRACE_DOC)).toBe(GOLDEN_TRACE_CANONICAL);
  });

  it('computes the engine CIDv1(raw, sha2-256) values', () => {
    expect(cidV1RawSha256Utf8(GOLDEN_TRACE_CANONICAL)).toBe(GOLDEN_TRACE_CID);
    expect(cidV1RawSha256Utf8('hello world')).toBe(GOLDEN_HELLO_CID);
  });

  it('computes the engine evidence packet digest', () => {
    expect(sha256DigestOfCanonicalJson(GOLDEN_PACKET)).toBe(
      GOLDEN_PACKET_DIGEST,
    );
  });

  it('drops undefined object values and rejects non-finite numbers', () => {
    expect(canonicalJsonString({ b: 1, a: undefined })).toBe('{"b":1}');
    expect(() => canonicalJsonString({ n: Number.POSITIVE_INFINITY })).toThrow(
      /non-finite/,
    );
  });
});

describe('serializeToolCallTrace', () => {
  it('pairs tool calls with their results by tool_call_id', () => {
    const doc = serializeToolCallTrace(goldenHistory(), {
      sessionId: 's-1',
      requestId: 'r-1',
    });
    expect(doc).toEqual(GOLDEN_TRACE_DOC);
  });

  it('marks unanswered calls pending and failed results as error', () => {
    const messages: BaseMessage[] = [
      new AIMessage({
        content: '',
        tool_calls: [
          { id: 'call-a', name: 'tool_a', args: {} },
          { id: 'call-b', name: 'tool_b', args: { x: 1 } },
        ],
      }),
      new ToolMessage({
        content: 'boom',
        tool_call_id: 'call-a',
        name: 'tool_a',
        status: 'error',
      }),
    ];
    const doc = serializeToolCallTrace(messages, {
      sessionId: 's',
      requestId: 'r',
    });
    expect(doc.toolCalls).toEqual([
      {
        id: 'call-a',
        name: 'tool_a',
        args: {},
        output: 'boom',
        status: 'error',
      },
      { id: 'call-b', name: 'tool_b', args: { x: 1 }, status: 'pending' },
    ]);
  });
});

describe('captureTrace', () => {
  it('posts the trace document to the session room and returns a recomputable ref', async () => {
    const postToRoom = vi.fn(async () => '$event-1');
    const ctx = traceCtx(goldenHistory(), {
      matrix: {
        postToRoom,
        getRoomState: async (roomId: string) => ({ roomId, state: [] }),
        getEventById: async (_roomId: string, eventId: string) => ({
          eventId,
          type: 'm.room.message',
          content: {},
        }),
      },
    });

    const result = await captureTrace(ctx);
    expect(result).toEqual({
      uri: 'matrix:roomid/room%3Aixo.world/e/event-1',
      cid: GOLDEN_TRACE_CID,
    });

    expect(postToRoom).toHaveBeenCalledTimes(1);
    const [roomId, content] = postToRoom.mock.calls[0]! as [
      string,
      Record<string, unknown>,
    ];
    expect(roomId).toBe('!room:ixo.world');
    const payload = content[TRACE_EVENT_KEY] as {
      cid: string;
      document: unknown;
    };
    expect(payload.cid).toBe(GOLDEN_TRACE_CID);
    // An auditor recomputes the CID from the posted document and matches.
    expect(cidV1RawSha256Utf8(canonicalJsonString(payload.document))).toBe(
      GOLDEN_TRACE_CID,
    );
  });

  it('returns an error when the invocation has no session room', async () => {
    const ctx = makeRuntimeContext({
      history: {
        messages: goldenHistory(),
        recent: () => [],
        userContext: {},
        state: { messages: [] },
      },
    });
    const result = await captureTrace(ctx);
    expect(result).toMatchObject({ error: expect.stringContaining('room') });
  });

  it('returns an error when posting to Matrix fails', async () => {
    const ctx = traceCtx(goldenHistory(), {
      matrix: {
        postToRoom: async () => {
          throw new Error('federation is down');
        },
        getRoomState: async (roomId: string) => ({ roomId, state: [] }),
        getEventById: async (_roomId: string, eventId: string) => ({
          eventId,
          type: 'm.room.message',
          content: {},
        }),
      },
    });
    const result = await captureTrace(ctx);
    expect(result).toMatchObject({
      error: expect.stringContaining('federation is down'),
    });
  });

  it('builds MSC2312 matrix URIs with sigils stripped and segments encoded', () => {
    expect(matrixEventUri('!abc:ixo.world', '$evt/1')).toBe(
      'matrix:roomid/abc%3Aixo.world/e/evt%2F1',
    );
  });
});

describe('evidence builders', () => {
  it('builds a fact with honest defaults (supports, reported, usable, client_assisted)', () => {
    const fact = buildStructuredFact({
      factId: 'fact:1',
      factType: 'coding_task.tests_passed',
      statement: 'All 27 tests passed.',
      subject: 'urn:test:run:1',
      predicate: 'conclusion',
      object: 'success',
      source: { evidenceId: 'urn:ixo:evidence:test-1', locator: '$.summary' },
    });
    expect(fact).toEqual(GOLDEN_PACKET.facts[0]);
  });

  it('preserves an explicit server_verified provenance', () => {
    const fact = buildStructuredFact({
      factId: 'fact:2',
      factType: 'coding_task.ci_passed',
      statement: 'CI concluded success.',
      subject: 'urn:ci:run:9',
      predicate: 'conclusion',
      object: 'success',
      modality: 'externally_verified',
      source: {
        evidenceId: 'urn:ixo:evidence:test-1',
        locator: '$.run.conclusion',
        origin: {
          apiOrigin: 'ci_provider',
          provenanceClass: 'server_verified',
        },
      },
    });
    expect(fact.source.origin?.provenanceClass).toBe('server_verified');
    expect(fact.source.origin?.apiOrigin).toBe('ci_provider');
  });

  it('builds a schema-valid packet and rejects empty fact lists', () => {
    const packet = buildEvidencePacket({
      claimId: 'claim-1',
      packetId: 'urn:ixo:evidence:test-1',
      facts: [
        buildStructuredFact({
          factId: 'fact:1',
          factType: 'coding_task.tests_passed',
          statement: 'All 27 tests passed.',
          subject: 'urn:test:run:1',
          predicate: 'conclusion',
          object: 'success',
          source: {
            evidenceId: 'urn:ixo:evidence:test-1',
            locator: '$.summary',
          },
        }),
      ],
    });
    expect(packet).toEqual(GOLDEN_PACKET);
    expect(() =>
      buildEvidencePacket({
        claimId: 'claim-1',
        packetId: 'urn:ixo:evidence:empty',
        facts: [],
      }),
    ).toThrow();
  });

  it('builds an envelope whose integrity digest matches the engine convention', () => {
    const envelope = buildEvidenceEnvelope({
      evidenceId: 'urn:ixo:evidence:test-1',
      claimId: 'claim-1',
      submitterDid: 'did:ixo:oracle:qiforge',
      packet: GOLDEN_PACKET as never,
    });
    expect(envelope).toEqual({
      schema: 'oracle.evidence-envelope.v1',
      evidenceId: 'urn:ixo:evidence:test-1',
      claimId: 'claim-1',
      mediaType: FACT_PACKET_MEDIA_TYPE,
      submitter: { did: 'did:ixo:oracle:qiforge' },
      integrity: {
        sha256: GOLDEN_PACKET_DIGEST,
        signatureStatus: 'absent',
      },
    });
  });
});

describe('evaluate_claim trace and evidence wiring', () => {
  const fetchSpy = vi.spyOn(globalThis, 'fetch');

  afterEach(() => {
    fetchSpy.mockReset();
  });

  const VALID_ARGS = {
    deed: { id: 'deed-1', aud: 'did:example:aud' },
    claim: {
      id: 'claim-1',
      cap: 'urn:cap:test',
      jti: 'jti-1',
      automatedAgent: true,
      proposedPatch: { status: 'done' },
    },
    rubric: {
      rubricVersionId: 'rubric-v1',
      thresholdBps: 7000,
      mode: 'fail_any_dimension',
      patchAllowlist: ['status'],
      requireTraceForAutomated: true,
    },
  };

  function evaluateTool(
    ctx = makeBuildCtx({ config: { EVALS_ENGINE_URL: 'https://evals.test' } }),
  ) {
    const plugin = new EvalsPlugin();
    const [subAgent] = plugin.getSubAgents(ctx);
    const tools =
      typeof subAgent!.tools === 'function'
        ? subAgent!.tools(ctx)
        : subAgent!.tools;
    return tools.find((t) => t.name === 'evaluate_claim')!;
  }

  it('captures and attaches claim.trace when attachTrace is set', async () => {
    fetchSpy.mockResolvedValueOnce(
      new Response(
        JSON.stringify({
          jobId: 'job-1',
          claimId: 'claim-1',
          status: 'pending',
        }),
        { status: 202 },
      ),
    );
    fetchSpy.mockResolvedValueOnce(
      new Response(
        JSON.stringify({
          id: 'job-1',
          status: 'pending',
          error: null,
          attempts: 1,
          lastError: null,
          resultSummary: null,
          createdAt: 1,
          updatedAt: 1,
        }),
        { status: 200 },
      ),
    );
    const ctx = traceCtx(goldenHistory());

    const result = await evaluateTool().handler(
      { ...VALID_ARGS, attachTrace: true, waitSeconds: 0 },
      ctx,
    );
    expect(result).toMatchObject({ status: 'pending' });

    const body = JSON.parse(String(fetchSpy.mock.calls[0]![1]?.body)) as {
      claim: { trace?: { uri: string; cid: string } };
    };
    expect(body.claim.trace).toEqual({
      uri: 'matrix:roomid/room%3Aixo.world/e/event-id',
      cid: GOLDEN_TRACE_CID,
    });
    expect(body).not.toHaveProperty('attachTrace');
  });

  it('keeps a caller-supplied trace instead of capturing', async () => {
    fetchSpy.mockResolvedValueOnce(
      new Response(
        JSON.stringify({
          jobId: 'job-1',
          claimId: 'claim-1',
          status: 'failed',
          error: 'x',
        }),
        { status: 202 },
      ),
    );
    const postToRoom = vi.fn(async () => '$never');
    const ctx = traceCtx(goldenHistory(), {
      matrix: {
        postToRoom,
        getRoomState: async (roomId: string) => ({ roomId, state: [] }),
        getEventById: async (_r: string, eventId: string) => ({
          eventId,
          type: 'm.room.message',
          content: {},
        }),
      },
    });

    const supplied = { uri: 'trace://external/1', cid: 'bafkexternal' };
    await evaluateTool().handler(
      {
        ...VALID_ARGS,
        claim: { ...VALID_ARGS.claim, trace: supplied },
        attachTrace: true,
      },
      ctx,
    );
    expect(postToRoom).not.toHaveBeenCalled();
    const body = JSON.parse(String(fetchSpy.mock.calls[0]![1]?.body)) as {
      claim: { trace: unknown };
    };
    expect(body.claim.trace).toEqual(supplied);
  });

  it('fails attachTrace without a session room, before any submission', async () => {
    const ctx = makeRuntimeContext();
    const result = await evaluateTool().handler(
      { ...VALID_ARGS, attachTrace: true },
      ctx,
    );
    expect(result).toMatchObject({ error: expect.stringContaining('room') });
    expect(fetchSpy).not.toHaveBeenCalled();
  });

  it('rejects evidence whose packet claimId mismatches claim.id before submission', async () => {
    const result = await evaluateTool().handler(
      {
        ...VALID_ARGS,
        evidence: { packet: { ...GOLDEN_PACKET, claimId: 'other-claim' } },
      },
      makeRuntimeContext(),
    );
    expect(result).toMatchObject({ error: 'evidence_claim_binding_mismatch' });
    expect(fetchSpy).not.toHaveBeenCalled();
  });
});
